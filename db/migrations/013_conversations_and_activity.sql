CREATE INDEX IF NOT EXISTS idx_activity_log_tenant ON activity_log(tenant_id, created_at);
CREATE INDEX IF NOT EXISTS idx_activity_log_agent ON activity_log(tenant_id, agent, created_at);

ALTER TABLE activity_log ENABLE ROW LEVEL SECURITY;
CREATE POLICY tenant_iso_activity_log ON activity_log FOR ALL
  USING (tenant_id = current_setting('app.tenant_id', true)::uuid);

